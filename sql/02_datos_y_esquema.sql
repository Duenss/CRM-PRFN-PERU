-- 3) Mensajes del bot de WhatsApp ----------------------------
create table if not exists public.mensajes (
  id bigint generated by default as identity primary key,
  cliente_id text,
  telefono text not null,
  direccion text not null check (direccion in ('entrante', 'saliente')),
  texto text not null,
  origen text not null default 'bot',
  estado text not null default 'ok',
  creado_en timestamptz not null default now()
);

create index if not exists mensajes_telefono_idx on public.mensajes (telefono, creado_en desc);
create index if not exists mensajes_cliente_idx on public.mensajes (cliente_id);

-- 4) Ayudas para el calendario -------------------------------
-- fecha_programada ya existe. Aseguramos el índice para el calendario.
alter table public.campanas add column if not exists numero_emisor text;
create index if not exists campanas_fecha_programada_idx on public.campanas (fecha_programada);
create index if not exists clientes_cumpleanos_idx on public.clientes (fecha_cumpleanos);
create unique index if not exists clientes_telefono_key on public.clientes (telefono);

commit;